#!/usr/bin/env python3
"""Writes test/vp_vocab_en_us.h: the selectable rows of the recording script (docs/features/08).

Run from the repository root:
    python components/core/voice_pack/test/gen_vocab_header.py
The header is checked in; regenerate it when recording-script.csv gains or loses a selectable row.
"""
import csv
import pathlib

root = pathlib.Path(__file__).resolve().parents[4]
src = root / "docs/features/08-Audio-and-Annunciation/recording-script.csv"
dst = pathlib.Path(__file__).resolve().parent / "vp_vocab_en_us.h"
cats = {"position": 1, "location": 2, "object": 3, "number": 4}
rows = [r for r in csv.DictReader(open(src, encoding="utf-8")) if r["category"] in cats]
out = ["/* Generated by gen_vocab_header.py from recording-script.csv: do not edit. */",
       "#ifndef VP_VOCAB_EN_US_H", "#define VP_VOCAB_EN_US_H", "",
       "#define VP_VOCAB_EN_US_COUNT %du" % len(rows), "",
       "static const struct { const char *key; unsigned char category; const char *text; } vp_vocab_en_us[] = {"]
for r in rows:
    out.append('    {"%s", %d, "%s"},' % (r["clip_id"], cats[r["category"]], r["text"]))
out += ["};", "", "#endif", ""]
dst.write_text("\n".join(out), encoding="utf-8")
print("wrote", dst, len(rows))
