/*
 * zw_crypto.c - the crypto port's start-up self-test (see zw_crypto.h, "The port's own check";
 * docs/features/36 ZW-008): the standards' known answers for the two primitives that compute, and
 * a random source that is not stuck. The vectors are the ones test/test_zw_crypto.c proves the PC
 * port with.
 */
#include "zw_crypto_internal.h"

/* FIPS-197 (2001) appendix C.1, AES-128: key, plaintext, ciphertext. */
static const uint8_t AES_KEY[16] = {
    0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07,
    0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f,
};
static const uint8_t AES_IN[16] = {
    0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77,
    0x88, 0x99, 0xaa, 0xbb, 0xcc, 0xdd, 0xee, 0xff,
};
static const uint8_t AES_OUT[16] = {
    0x69, 0xc4, 0xe0, 0xd8, 0x6a, 0x7b, 0x04, 0x30,
    0xd8, 0xcd, 0xb7, 0x80, 0x70, 0xb4, 0xc5, 0x5a,
};

/* RFC 7748 §5.2, the first X25519 vector: scalar, u-coordinate, result. */
static const uint8_t X_SCALAR[32] = {
    0xa5, 0x46, 0xe3, 0x6b, 0xf0, 0x52, 0x7c, 0x9d,
    0x3b, 0x16, 0x15, 0x4b, 0x82, 0x46, 0x5e, 0xdd,
    0x62, 0x14, 0x4c, 0x0a, 0xc1, 0xfc, 0x5a, 0x18,
    0x50, 0x6a, 0x22, 0x44, 0xba, 0x44, 0x9a, 0xc4,
};
static const uint8_t X_U[32] = {
    0xe6, 0xdb, 0x68, 0x67, 0x58, 0x30, 0x30, 0xdb,
    0x35, 0x94, 0xc1, 0xa4, 0x24, 0xb1, 0x5f, 0x7c,
    0x72, 0x66, 0x24, 0xec, 0x26, 0xb3, 0x35, 0x3b,
    0x10, 0xa9, 0x03, 0xa6, 0xd0, 0xab, 0x1c, 0x4c,
};
static const uint8_t X_OUT[32] = {
    0xc3, 0xda, 0x55, 0x37, 0x9d, 0xe9, 0xc6, 0x90,
    0x8e, 0x94, 0xea, 0x4d, 0xf2, 0x8d, 0x08, 0x4f,
    0x32, 0xec, 0xcf, 0x03, 0x49, 0x1c, 0x71, 0xf7,
    0x54, 0xb4, 0x07, 0x55, 0x77, 0xa2, 0x85, 0x52,
};

/* RFC 7748 §6.1: Alice's private key, and her public key X25519(private, 9). */
static const uint8_t ALICE_PRIV[32] = {
    0x77, 0x07, 0x6d, 0x0a, 0x73, 0x18, 0xa5, 0x7d,
    0x3c, 0x16, 0xc1, 0x72, 0x51, 0xb2, 0x66, 0x45,
    0xdf, 0x4c, 0x2f, 0x87, 0xeb, 0xc0, 0x99, 0x2a,
    0xb1, 0x77, 0xfb, 0xa5, 0x1d, 0xb9, 0x2c, 0x2a,
};
static const uint8_t ALICE_PUB[32] = {
    0x85, 0x20, 0xf0, 0x09, 0x89, 0x30, 0xa7, 0x54,
    0x74, 0x8b, 0x7d, 0xdc, 0xb4, 0x3e, 0xf7, 0x5a,
    0x0d, 0xbf, 0x3a, 0x0d, 0x26, 0x38, 0x1a, 0xf4,
    0xeb, 0xa4, 0xa9, 0x8e, 0xaa, 0x9b, 0x4e, 0x6a,
};

/* The base point: u = 9, little-endian. */
static const uint8_t BASE[32] = {9};

/* The outputs start all zero, which no expected answer is: an answer the port never wrote cannot
 * pass. */
static bool aes_ok(const zw_crypto_port_t *port)
{
    uint8_t out[16] = {0};
    return port->aes128_encrypt(port->ctx, AES_KEY, AES_IN, out) &&
           zw_ct_equal(out, AES_OUT, sizeof out);
}

static bool x25519_ok(const zw_crypto_port_t *port, const uint8_t scalar[32],
                      const uint8_t point[32], const uint8_t want[32])
{
    uint8_t out[32] = {0};
    return port->x25519(port->ctx, out, scalar, point) && zw_ct_equal(out, want, sizeof out);
}

/* Two draws, neither all zero nor the same: a source stuck at one value, or one that writes
 * nothing, is caught (a working one fails this about once in 2^127 starts). */
static bool random_ok(const zw_crypto_port_t *port)
{
    static const uint8_t zero[16] = {0};
    uint8_t a[16] = {0}, b[16] = {0};
    const bool ok = port->random(port->ctx, a, sizeof a) && port->random(port->ctx, b, sizeof b) &&
                    !zw_ct_equal(a, zero, sizeof a) && !zw_ct_equal(b, zero, sizeof b) &&
                    !zw_ct_equal(a, b, sizeof a);
    zw_wipe(a, sizeof a);
    zw_wipe(b, sizeof b);
    return ok;
}

bool zw_crypto_port_check(const zw_crypto_port_t *port)
{
    return port != NULL && port->aes128_encrypt != NULL && port->x25519 != NULL &&
           port->random != NULL && aes_ok(port) && x25519_ok(port, X_SCALAR, X_U, X_OUT) &&
           x25519_ok(port, ALICE_PRIV, BASE, ALICE_PUB) && random_ok(port);
}
