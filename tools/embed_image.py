#!/usr/bin/env python3
"""
embed_image.py - turn a baseline JPEG into a C array for the touch UI (components/ui/alarm_ui/images).

The UI decodes it once at runtime with LVGL's TJPGD decoder (components/ui/alarm_ui/src/ui_saver.c),
so the firmware carries the JPEG (about 130 KB) instead of a 1.2 MB RGB565 bitmap. TJPGD only
reads baseline JPEGs: progressive files are rejected here.

Usage:
    python tools/embed_image.py components/ui/alarm_ui/images/saver_forest.jpg
    python tools/embed_image.py --check components/ui/alarm_ui/images/saver_forest.jpg

writes (or checks) images/saver_forest_jpg.c next to the JPEG, with
    const uint8_t ui_img_saver_forest_jpg[];
    const uint32_t ui_img_saver_forest_jpg_size;
"""

import argparse
import re
import struct
import sys
from pathlib import Path


def jpeg_info(data):
    """(width, height) of a baseline JPEG; raises ValueError otherwise."""
    if data[:2] != b"\xff\xd8":
        raise ValueError("not a JPEG")
    i = 2
    while i + 4 <= len(data):
        if data[i] != 0xFF:
            raise ValueError("broken JPEG marker at %d" % i)
        marker = data[i + 1]
        if marker == 0xD8 or 0xD0 <= marker <= 0xD7 or marker == 0x01:
            i += 2
            continue
        length = struct.unpack(">H", data[i + 2:i + 4])[0]
        if marker == 0xC0:
            height, width = struct.unpack(">HH", data[i + 5:i + 9])
            return width, height
        if 0xC1 <= marker <= 0xCF and marker not in (0xC4, 0xC8, 0xCC):
            raise ValueError("not a baseline JPEG (SOF%d): save it as baseline" % (marker - 0xC0))
        i += 2 + length
    raise ValueError("no frame header found")


def c_source(jpg, data, width, height):
    symbol = "ui_img_" + re.sub(r"[^0-9a-zA-Z]", "_", jpg.stem) + "_jpg"
    lines = [
        "/* Generated by tools/embed_image.py from %s (%dx%d baseline JPEG, %d bytes).",
        " * Do not edit: change the JPEG and run the tool again. */",
        "#include <stdint.h>",
        "",
        "const uint32_t %s_size = %d;",
        "const uint8_t %s[] = {",
    ]
    out = [lines[0] % (jpg.name, width, height, len(data)), lines[1], lines[2], lines[3],
           lines[4] % (symbol, len(data)), lines[5] % symbol]
    for k in range(0, len(data), 16):
        out.append("    " + ", ".join("0x%02X" % b for b in data[k:k + 16]) + ",")
    out.append("};")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser(description="Embed a baseline JPEG for the UI as a C array.")
    ap.add_argument("jpeg", nargs="+", help="JPEG files")
    ap.add_argument("--check", action="store_true", help="fail if a C file is missing or stale")
    args = ap.parse_args()
    stale = 0
    for name in args.jpeg:
        jpg = Path(name)
        data = jpg.read_bytes()
        try:
            width, height = jpeg_info(data)
        except ValueError as e:
            sys.exit("%s: %s" % (jpg, e))
        out = jpg.with_name(jpg.stem + "_jpg.c")
        text = c_source(jpg, data, width, height)
        current = out.read_text(encoding="utf-8") if out.exists() else None
        if current == text:
            continue
        if args.check:
            print("%s is stale: run tools/embed_image.py %s" % (out, jpg))
            stale += 1
        else:
            out.write_text(text, encoding="utf-8", newline="\n")
            print("%s: %dx%d, %d bytes -> %s" % (jpg, width, height, len(data), out))
    sys.exit(1 if stale else 0)


if __name__ == "__main__":
    main()
