#!/usr/bin/env python3
"""Embed the rail logo's P5 alpha mask as a tintable LVGL A8 image (no dependencies)."""
import argparse
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    directory = Path(__file__).resolve().parents[1] / 'components/ui/alarm_ui/images'
    source = directory / 'roboalarms_mark.pgm'
    magic, dimensions, maximum, pixels = source.read_bytes().split(b'\n', 3)
    width, height = map(int, dimensions.split())
    if magic != b'P5' or maximum != b'255' or (width, height) != (44, 44) or len(pixels) != width * height:
        raise SystemExit('Expected the 44x44 P5 alpha mask with max value 255')
    rows = ['    ' + ', '.join(f'0x{value:02X}' for value in pixels[i:i+16]) + ','
            for i in range(0, len(pixels), 16)]
    text = '\n'.join([
        '/* Generated by tools/embed_logo.py from roboalarms_mark.pgm. Do not edit. */',
        '#include "lvgl.h"', '',
        'static const uint8_t pixels[] = {', *rows, '};', '',
        'const lv_image_dsc_t ui_img_roboalarms_mark = {',
        '    .header = { .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8,',
        f'                .w = {width}, .h = {height}, .stride = {width} }},',
        '    .data_size = sizeof(pixels),', '    .data = pixels,', '};', '',
    ])
    output = directory / 'roboalarms_mark_a8.c'
    if args.check:
        if not output.exists() or output.read_text(encoding='utf-8') != text:
            raise SystemExit('Rail logo is stale: run python tools/embed_logo.py')
    else:
        output.write_text(text, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
